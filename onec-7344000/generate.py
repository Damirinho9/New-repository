def patch_form_node(node):
    if isinstance(node,dict):
        path=node.get("path")
        if path in {"Объект.ДатаЗаезда","Объект.ДатаВыезда","Объект.Комната","Объект.Тариф"}:
            node["events"]={"OnChange":"ШапкаПриИзменении"}
        if path in {"Объект.Услуги.Услуга","Объект.Услуги.Количество","Объект.Услуги.Цена"}:
            node["events"]={"OnChange":"УслугиПриИзменении"}
        if path=="Объект.Услуги":
            node["events"]={
                "AfterDeleteRow":"УслугиПослеУдаления",
                "OnEditEnd":"УслугиПриОкончанииРедактирования"
            }
        if path in {
            "Объект.КоличествоСуток","Объект.СтоимостьСуток","Объект.СуммаПроживания",
            "Объект.СуммаДополнительныхУслуг","Объект.ИтоговаяСумма","Объект.Услуги.Сумма"
        }:
            node["readOnly"]=True
        for value in node.values():
            patch_form_node(value)
    elif isinstance(node,list):
        for value in node:
            patch_form_node(value)

