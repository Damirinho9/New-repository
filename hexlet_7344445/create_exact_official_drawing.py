import os, sys, pathlib, hashlib, json
sys.path.append('/opt/ascon/kompas3d-v25/Bin')
from constants import constants as c
import ksapi

OUT=pathlib.Path('native_drawing_exact')
OUT.mkdir(exist_ok=True)
target=(OUT/'Hexlet_KOMPAS3D_Privet_Hexlet.cdw').resolve()
reopened=(OUT/'Hexlet_KOMPAS3D_Privet_Hexlet_REOPENED.cdw').resolve()

print('STEP=OPEN_INVISIBLE_EXACT_OFFICIAL_PATTERN')
app=ksapi.OpenKompasInvisible()
print('APP=',app)
if app is None: raise SystemExit('OpenKompasInvisible returned None')
print('APP_NAME=',app.GetApplicationName(True))
print('BUILD=',app.GetBuildNumber())

documents=app.GetDocuments()
print('DOCUMENTS=',documents)
if not documents: raise SystemExit('GetDocuments returned None')

doc=documents.AddWithDefaultSettings(c.ksDocumentDrawing, True)
print('DOC=',doc)
if doc is None: raise SystemExit('OFFICIAL_PATTERN_ADD_RETURNED_NONE')
print('DOC_TYPE=',doc.GetDocumentType())

d2=ksapi.IKompasDocument2D(doc)
mgr=d2.GetViewsAndLayersManager()
views=mgr.GetViews()
view=views.GetActiveView()
dc=ksapi.IDrawingContainer(view)
texts=dc.GetDrawingTexts()
print('TEXT_COUNT_BEFORE=',texts.GetCount())

t=texts.Add()
t.SetX(60.0); t.SetY(120.0)
line=ksapi.IText(t).Add()
item=line.Add()
item.SetStr('Привет, Хекслет!')
try: ksapi.ITextFont(item).SetHeight(10.0)
except Exception as exc: print('FONT_WARN=',type(exc).__name__,str(exc))
if not t.Update(): raise SystemExit('DrawingText.Update failed')
print('TEXT_COUNT_AFTER=',texts.GetCount())

print('SAVE=',doc.SaveAs(str(target)))
if not target.exists() or target.stat().st_size==0: raise SystemExit('CDW_SAVE_FAILED')
print('TARGET_SIZE=',target.stat().st_size)
print('TARGET_SHA256=',hashlib.sha256(target.read_bytes()).hexdigest())
doc.Close(c.kdDoNotSaveChanges)
app.Quit()
print('CLOSED_FIRST')

app2=ksapi.OpenKompasInvisible()
if app2 is None: raise SystemExit('REOPEN_APP_NONE')
docs2=app2.GetDocuments()
doc2=docs2.Open(str(target),False,False)
print('REOPEN_DOC=',doc2)
if doc2 is None: raise SystemExit('REOPEN_DOC_NONE')
print('REOPEN_TYPE=',doc2.GetDocumentType())
rd2=ksapi.IKompasDocument2D(doc2)
rview=rd2.GetViewsAndLayersManager().GetViews().GetActiveView()
rdc=ksapi.IDrawingContainer(rview)
cnt=rdc.GetDrawingTexts().GetCount()
print('REOPEN_TEXT_COUNT=',cnt)
if cnt<1: raise SystemExit('REOPEN_TEXT_MISSING')
print('RESAVE=',doc2.SaveAs(str(reopened)))
if not reopened.exists() or reopened.stat().st_size==0: raise SystemExit('RESAVE_FAILED')
print('REOPENED_SHA256=',hashlib.sha256(reopened.read_bytes()).hexdigest())

result={'result':'PASS_NATIVE_DRAWING_SAVE_CLOSE_REOPEN','document_type':doc2.GetDocumentType(),'text_count':cnt,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'reopened_sha256':hashlib.sha256(reopened.read_bytes()).hexdigest()}
(OUT/'validation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
print('RESULT=PASS_NATIVE_DRAWING_SAVE_CLOSE_REOPEN')
doc2.Close(c.kdDoNotSaveChanges)
app2.Quit()
